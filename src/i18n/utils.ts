export function getLocaleFromUrl(url: URL): Lang {
  const [, lang] = url.pathname.split('/');
  if (lang in ui) return lang as Lang;
  return defaultLang;
}

export function useTranslations(lang: Lang) {
  return function t(key: keyof typeof ui[typeof defaultLang]) {
    return ui[lang][key] || ui[defaultLang][key] || key;
  };
}

export function getLocalizedRoute(route: string, lang: Lang): string {
  const routes: Record<string, Record<Lang, string>> = {
    '': { en: '/en/', ca: '/ca/' },
    'career': { en: '/en/career', ca: '/ca/carrera' },
    'projects': { en: '/en/projects', ca: '/ca/projectes' },
    'about_me': { en: '/en/about', ca: '/ca/sobre-mi' },
  };
  return routes[route]?.[lang] || `/${lang}/${route}`;
}
